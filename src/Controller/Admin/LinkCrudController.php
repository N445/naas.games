<?php

namespace App\Controller\Admin;

use App\Entity\Link\Link;
use App\Repository\Link\LinkRepository;
use Doctrine\ORM\EntityManagerInterface;
use EasyCorp\Bundle\EasyAdminBundle\Controller\AbstractCrudController;
use EasyCorp\Bundle\EasyAdminBundle\Field\IdField;
use EasyCorp\Bundle\EasyAdminBundle\Field\NumberField;
use EasyCorp\Bundle\EasyAdminBundle\Field\TextEditorField;
use EasyCorp\Bundle\EasyAdminBundle\Field\TextField;
use EasyCorp\Bundle\EasyAdminBundle\Field\UrlField;

class LinkCrudController extends AbstractCrudController
{
    public function __construct(
        private readonly LinkRepository $linkRepository,
    )
    {
    }

    public static function getEntityFqcn(): string
    {
        return Link::class;
    }

    public function persistEntity(EntityManagerInterface $entityManager, $entityInstance): void
    {
        $lastLink = $this->linkRepository->createQueryBuilder('l')
            ->orderBy('l.display_order', 'DESC')
            ->setMaxResults(1)
            ->getQuery()
            ->getOneOrNullResult();

        $displayOrder = 10;
        if($lastLink){
            $displayOrder = $lastLink->getDisplayOrder() + 10;
        }

        $entityInstance->setDisplayOrder($displayOrder);
        parent::updateEntity($entityManager, $entityInstance); // TODO: Change the autogenerated stub
    }

    public function configureFields(string $pageName): iterable
    {
        return [
            TextField::new('title'),
            UrlField::new('url'),
            NumberField::new('displayOrder'),
        ];
    }
}
